# 只拦截明确的内部诊断说法，不禁止商品名称中含“数据库/知识库”等正常业务词汇。
_INTERNAL = re.compile(
    r'(?:我的|我们的|当前|现有)知识库|(?:根据|查询|查阅|检索).{0,6}知识库'
    r'|知识库.{0,14}(?:没有|未找到|未收录|找不到|查不到|显示|记载|记录|缺少|未提供|未包含)'
    r'|(?:系统提示词|工具调用|模型输出|模型调用失败|数据库查询失败|检索结果显示|内部审核事项)'
    r'|(?:数据库|检索).{0,8}(?:没有查到|未找到|失败|不可用)', re.I)


def contains_internal_diagnostics(text):
    return bool(_INTERNAL.search(text or ''))


def is_neutral_reaction(text):
    """仅独立、中性的表情不触发新一轮自动答话；投诉和含问题的消息不在此列。"""
    return isinstance(text,str) and text.strip() in {
        '[呆住]','[微笑]','[笑哭]','[捂脸]','[握手]', '😂','😅','😊','🙂','👍','👍🏻','👌','👌🏻',
    }
